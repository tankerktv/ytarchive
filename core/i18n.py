"""Выбор языка и перевод.

Ключами служат сами русские строки, а не выдуманные имена вроде
`window.tab.channels`. Причина простая: код остаётся читаемым. `_("Убрать")`
понятно без сверки со словарём, а `_("btn_remove_42")` — нет, и однажды
кто-нибудь переведёт не то.

Плата за это — хрупкость: поправив русскую строку в коде, легко осиротить
перевод. Поэтому полнота словарей проверяется тестом, а не доверием.

Здесь только выбор и подстановка. Ни Qt, ни файлов, ни определения системного
языка: язык приходит снаружи строкой. Так его можно проверить, не имея
ни системы с нужной локалью, ни установленного фреймворка.
"""

from __future__ import annotations

from collections.abc import Callable

#: Язык, на котором написан код. Его словаря нет и быть не может: строки
#: в исходнике уже на нём.
ИСХОДНЫЙ = "ru"

#: Чем отвечаем, когда язык неизвестен. Не исходным: человек, у которого
#: система на суахили, скорее прочтёт английский, чем русский.
ЗАПАСНОЙ = "en"

#: Значение настройки «взять у системы». Не пустая строка: пустая
#: неотличима от «настройку забыли», а это разные вещи.
СИСТЕМНЫЙ = "system"

#: Названия языков — каждое на своём языке. Показывать «Немецкий» тому, кто
#: ищет свой язык в списке, бессмысленно: он ищет слово «Deutsch».
НАЗВАНИЯ = {
    "ru": "Русский",
    "en": "English",
    "de": "Deutsch",
    "es": "Español",
    "fr": "Français",
    "pt": "Português",
    "it": "Italiano",
    "pl": "Polski",
    "uk": "Українська",
    "tr": "Türkçe",
    "zh": "中文",
    "ja": "日本語",
}


def нормализовать(код: str) -> str:
    """Привести обозначение языка к двухбуквенному.

    Системы называют язык по-разному: `ru_RU.UTF-8`, `en-GB`, `pt_BR`.
    Нам нужна только основа — держать отдельный словарь на каждую страну
    значило бы переводить одно и то же по десять раз.
    """
    if not код:
        return ""
    основа = код.strip().replace("_", "-").split("-", 1)[0]
    return основа.lower() if основа.isalpha() else ""


def resolve(requested: str, system: str, available) -> str:
    """Каким языком говорить.

    `requested` — что выбрано в настройках, `system` — что сообщила система,
    `available` — какие словари есть на самом деле.

    Порядок именно такой: выбор человека важнее системы, система важнее
    умолчания. Язык, которого нет в словарях, молча не подставляем — иначе
    интерфейс окажется наполовину на чужом языке.
    """
    есть = set(available) | {ИСХОДНЫЙ}

    выбранный = нормализовать(requested)
    if выбранный and выбранный != СИСТЕМНЫЙ and выбранный in есть:
        return выбранный

    системный = нормализовать(system)
    if системный in есть:
        return системный

    return ЗАПАСНОЙ if ЗАПАСНОЙ in есть else ИСХОДНЫЙ


def translator(language: str, catalogues: dict[str, dict[str, str]]) -> Callable[[str], str]:
    """Получить переводчик для языка.

    Незнакомая строка возвращается как есть. Падать на ней нельзя: пропущенный
    перевод — это некрасиво, а исключение посреди отрисовки окна — это конец
    работы. Ловит такие пропуски тест, а не пользователь.
    """
    словарь = {} if language == ИСХОДНЫЙ else catalogues.get(language, {})

    def перевести(строка: str) -> str:
        return словарь.get(строка, строка)

    return перевести


def missing(catalogue: dict[str, str], sources) -> list[str]:
    """Строки, которые есть в коде, но не переведены."""
    return sorted(с for с in set(sources) if с not in catalogue)


def orphaned(catalogue: dict[str, str], sources) -> list[str]:
    """Переводы, которым в коде уже ничего не соответствует.

    Осиротевший перевод — след правки русской строки. Сам по себе он безвреден,
    но означает, что где-то рядом появилась непереведённая.
    """
    известные = set(sources)
    return sorted(к for к in catalogue if к not in известные)
