"""Знак программы числами: ролик, лежащий в лотке.

Треугольник — «видео», лоток под ним — «сохранено». Вместе это и есть архив
роликов, а не просто «скачать».

Здесь только геометрия и её запись в SVG — без Qt. Рисует знак `gui/logo.py`,
а проверка «файл не отстал от описания» обязана идти и там, где Qt нет.
"""

from __future__ import annotations

#: Фирменный цвет — для окна, ярлыка и README. В трее вместо него цвет состояния.
ФИРМЕННЫЙ = "#8b5cf6"

#: Сетка, в которой заданы числа ниже. Те же числа стоят в `assets/logo.svg`.
СЕТКА = 160.0
СКРУГЛЕНИЕ = 36.0
ТРЕУГОЛЬНИК = ((58.0, 40.0), (58.0, 96.0), (106.0, 68.0))
ТОЛЩИНА_ТРЕУГОЛЬНИКА = 10.0
ЛОТОК = ((40.0, 102.0), (40.0, 122.0), (120.0, 122.0), (120.0, 102.0))
ТОЛЩИНА_ЛОТКА = 12.0


def svg(цвет: str = ФИРМЕННЫЙ) -> str:
    """Тот же знак текстом SVG — для README и ярлыка на Linux."""
    треугольник = " ".join(
        ("M" if номер == 0 else "L") + f"{x:g} {y:g}" for номер, (x, y) in enumerate(ТРЕУГОЛЬНИК)
    )
    лоток = " ".join(
        ("M" if номер == 0 else "L") + f"{x:g} {y:g}" for номер, (x, y) in enumerate(ЛОТОК)
    )
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {СЕТКА:g} {СЕТКА:g}" '
        f'width="{СЕТКА:g}" height="{СЕТКА:g}">\n'
        "  <title>ytarchive</title>\n"
        f'  <rect width="{СЕТКА:g}" height="{СЕТКА:g}" rx="{СКРУГЛЕНИЕ:g}" fill="{цвет}"/>\n'
        f'  <path d="{треугольник} Z" fill="#ffffff" stroke="#ffffff" '
        f'stroke-width="{ТОЛЩИНА_ТРЕУГОЛЬНИКА:g}" stroke-linejoin="round"/>\n'
        f'  <path d="{лоток}" fill="none" stroke="#ffffff" stroke-width="{ТОЛЩИНА_ЛОТКА:g}" '
        'stroke-linecap="round" stroke-linejoin="round"/>\n'
        "</svg>\n"
    )
