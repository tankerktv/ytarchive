"""Загрузка, которая говорит, но не продвигается.

Надзорщик опознаёт зависание по молчанию — и этого оказалось мало. 19.09.2026
ролик на полтора гигабайта тянулся пять часов: yt-dlp исправно печатал строки
прогресса, молчанием это не было, а остальные каналы всё это время ждали.

Здесь второе мерило: сколько байт прибавилось за последние N минут. Меньше
порога — загрузка «ползёт», её снимают и откладывают до следующего прохода.
Скачанное при этом не теряется: yt-dlp оставляет недокачанный файл и
продолжает с того же места.

Мерило — скорость, а не полная остановка. В том самом случае ролик не стоял,
он шёл примерно на 80 КБ/с при канале в десятки мегабит.

Только арифметика над отметками: ни часов, ни процессов. Отметки приходят
из разбора строк yt-dlp, время — от того, кто зовёт.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

#: Одна отметка: когда и сколько байт текущего файла уже скачано.
Sample = tuple[float, float]

_ID_В_ИМЕНИ = re.compile(r"\[([A-Za-z0-9_-]{11})\]\.[^\[\]]*$")


@dataclass(frozen=True)
class CrawlPolicy:
    """Когда считать загрузку ползущей.

    `min_speed` — байт в секунду, усреднённо за `window` секунд. Ноль
    выключает проверку: на медленной линии порог пришлось бы подбирать,
    а выключить честнее, чем гадать за человека.
    """

    window: float = 600.0
    min_speed: float = 100 * 1024

    def __post_init__(self) -> None:
        if self.window <= 0:
            raise ValueError("окно наблюдения должно быть положительным")
        if self.min_speed < 0:
            raise ValueError("порог скорости не может быть отрицательным")

    @property
    def enabled(self) -> bool:
        return self.min_speed > 0


def observe(samples: tuple[Sample, ...], now: float, done: float, window: float) -> tuple[Sample, ...]:
    """Добавить отметку и выбросить лишние старые.

    Одну отметку старше окна оставляем намеренно: по ней считается прирост
    за ПОЛНОЕ окно. Выбросив всё, что старше, мы мерили бы прирост за
    произвольный отрезок короче окна и снимали бы здоровую загрузку.
    """
    все = (*samples, (now, done))
    граница = now - window
    # Последняя отметка не моложе границы — с неё начинается окно.
    начало = 0
    for номер, (когда, _сколько) in enumerate(все):
        if когда <= граница:
            начало = номер
        else:
            break
    return все[начало:]


def is_crawling(samples: tuple[Sample, ...], now: float, policy: CrawlPolicy) -> bool:
    """Ползёт ли загрузка.

    Пока наблюдаем меньше окна — не судим: в начале файла скорость ещё
    неизвестна, и приговор по первым секундам был бы гаданием.

    Прирост считается от самой старой отметки до последней ИЗВЕСТНОЙ, а не
    до «сейчас»: если yt-dlp перестал печатать прогресс и только повторяет
    запросы, последняя отметка стареет, а прирост остаётся прежним — и это
    тоже ползущая загрузка.
    """
    if not policy.enabled or not samples:
        return False
    начало_времени, начало_байт = samples[0]
    if now - начало_времени < policy.window:
        return False
    прирост = samples[-1][1] - начало_байт
    # Оценка размера у yt-dlp плавает, и «скачано» может шагнуть назад.
    # Отрицательный прирост — это «не продвинулись», а не повод для паники.
    скорость = max(прирост, 0.0) / (now - начало_времени)
    return скорость < policy.min_speed


def done_bytes(percent: float | None, size_bytes: int | None) -> float | None:
    """Сколько байт скачано, по строке прогресса. None — строка не про то."""
    if percent is None or size_bytes is None:
        return None
    return percent / 100.0 * size_bytes


def video_id_from_path(path: str) -> str:
    """Идентификатор ролика из имени файла — он там в квадратных скобках.

    Пустая строка, если не нашёлся: тогда снятый ролик не удастся отложить
    поимённо, и вызывающий обязан это учесть, а не гадать.
    """
    найдено = _ID_В_ИМЕНИ.search(path)
    return найдено.group(1) if найдено else ""


#: Сколько ползущих роликов подряд терпим, прежде чем решить, что дело
#: не в роликах, а в линии. Два подряд — уже не совпадение.
SLOW_LINE_AFTER = 2


def line_is_slow(crawled_in_a_row: int) -> bool:
    """Ползёт всё подряд — значит, медленная линия, а не ролик.

    Снимать дальше бессмысленно: каждый следующий ролик потерял бы те же
    десять минут и был бы отложен так же. Проверку на этот проход выключают,
    а человеку говорят, что порог стоит поправить.
    """
    return crawled_in_a_row >= SLOW_LINE_AFTER
