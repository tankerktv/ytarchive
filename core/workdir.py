"""Смена рабочей папки: годится ли выбранное и чем это грозит.

Настройка выглядит безобидной — «куда складывать», — но внутри этой папки
лежит учёт скачанного. Указать пустую значит начать архив с нуля: программа
не будет знать ни одного ролика и заберёт всё заново. На нашем архиве это
1,27 ТБ и неделя выкачки.

Поэтому здесь не только «можно/нельзя», но и предупреждение словами: что
именно случится с той папкой, которую выбрали. Молчаливое согласие тут хуже
отказа — отказ человек заметит сразу, а тихую перекачку через сутки.

Файлы не переносятся. Никогда: перенос терабайта — не то, что программа
вправе затеять сама, пока человек смотрит на диалог.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class FolderCheck:
    """Приговор папке. `warning` не пустое и при `ok` — это не отказ,
    а то, что человек обязан прочитать до согласия."""

    ok: bool
    reason: str = ""
    warning: str = ""


def judge_folder(
    *,
    exists: bool,
    is_dir: bool,
    writable: bool,
    has_archive: bool,
    archive_count: int = 0,
    files_inside: int = 0,
    same_as_now: bool = False,
) -> FolderCheck:
    """Годится ли папка под архив и о чём предупредить.

    Ничего не трогает и в файловую систему не смотрит: факты передаются
    снаружи, чтобы решение можно было проверить без дисков и без прав.
    """
    if same_as_now:
        return FolderCheck(ok=False, reason="это и есть нынешняя рабочая папка")
    if not exists:
        return FolderCheck(ok=False, reason="папки нет")
    if not is_dir:
        return FolderCheck(ok=False, reason="это файл, а не папка")
    if not writable:
        return FolderCheck(ok=False, reason="в эту папку нельзя писать")

    хвост = (
        " Уже скачанное остаётся на прежнем месте — программа файлы не переносит."
    )

    if has_archive:
        return FolderCheck(
            ok=True,
            warning=(
                f"В этой папке уже есть учёт на {archive_count} роликов — "
                f"выкачка продолжит его." + хвост
            ),
        )

    if files_inside:
        return FolderCheck(
            ok=True,
            warning=(
                "В папке есть файлы, но учёта скачанного в ней нет. Программа "
                "не сможет понять, что из них уже забрано, и скачает всё заново."
                + хвост
            ),
        )

    return FolderCheck(
        ok=True,
        warning=(
            "Папка пуста: учёт начнётся с нуля, и все ролики будут скачаны "
            "заново — это часы и сотни гигабайт." + хвост
        ),
    )
