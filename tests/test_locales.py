"""Полнота словарей.

Пропущенный перевод ничего не ломает: строка просто останется по-русски.
Именно поэтому нужна проверка — сам по себе такой пропуск не всплывёт
никогда, а человек увидит чужой язык посреди своего и решит, что программа
недоделана. Так оно и будет.

Осиротевший перевод — обратный след: русскую строку в коде поправили,
а словарь остался прежним. Значит рядом наверняка появилась непереведённая.
"""

import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tools"))

from core.i18n import НАЗВАНИЯ, missing, orphaned  # noqa: E402
from core.locales import КАТАЛОГИ  # noqa: E402
from i18n_strings import собрать  # noqa: E402

НАДПИСИ = собрать()


def test_надписи_вообще_нашлись():
    """Пустой список сделал бы все проверки ниже бессмысленно зелёными."""
    assert len(НАДПИСИ) > 100


@pytest.mark.parametrize("язык", sorted(КАТАЛОГИ))
def test_словарь_полон(язык):
    нет = missing(КАТАЛОГИ[язык], НАДПИСИ)
    assert not нет, f"в словаре «{язык}» не хватает {len(нет)}: {нет[:5]}"


@pytest.mark.parametrize("язык", sorted(КАТАЛОГИ))
def test_в_словаре_нет_лишнего(язык):
    лишние = orphaned(КАТАЛОГИ[язык], НАДПИСИ)
    assert not лишние, (
        f"в словаре «{язык}» {len(лишние)} ключей, которых нет в коде — "
        f"похоже, русскую строку правили без словаря: {лишние[:5]}"
    )


@pytest.mark.parametrize("язык", sorted(КАТАЛОГИ))
def test_переводы_не_пустые(язык):
    пустые = [к for к, з in КАТАЛОГИ[язык].items() if not з.strip()]
    assert not пустые, f"в «{язык}» пустые переводы: {пустые[:5]}"


@pytest.mark.parametrize("язык", sorted(КАТАЛОГИ))
def test_подстановки_сохранены(язык):
    """Число дырок `{}` обязано совпасть. Потерянная дырка — это `IndexError`
    в момент показа, а лишняя — пустое место вместо числа.
    """
    беды = []
    for ключ, перевод in КАТАЛОГИ[язык].items():
        if ключ.count("{") != перевод.count("{") or ключ.count("}") != перевод.count("}"):
            беды.append(ключ)
    assert not беды, f"в «{язык}» разошлись подстановки: {беды[:5]}"


@pytest.mark.parametrize("язык", sorted(КАТАЛОГИ))
def test_у_каждого_словаря_есть_название_языка(язык):
    # Иначе язык нельзя показать в списке выбора.
    assert язык in НАЗВАНИЯ


def test_переводы_отличаются_от_исходника():
    """Словарь, целиком повторяющий русский, — это забытая работа,
    а не язык. Пара совпадений законна («логотип» → «Logo»), но не всё.
    """
    for язык, словарь in КАТАЛОГИ.items():
        совпало = sum(1 for к, з in словарь.items() if к == з)
        assert совпало < len(словарь) // 4, f"словарь «{язык}» почти не переведён"


# --- имя переводчика не должно затираться -----------------------------------


def test_имя_переводчика_нигде_не_занято():
    """Настоящий случай 03.09: в `cmd_check` стояло `решение, _ = probe(...)`,
    и переводчик оказывался `None`. Падало это не при разборе, а при первом же
    вызове — то есть у человека, а не в сборке.

    Проверяем механически: в файлах, где зовут `_()`, имя `_` не должно
    связываться ни присваиванием, ни распаковкой, ни доводом функции.
    """
    import ast

    from i18n_strings import ФАЙЛЫ

    корень = Path(__file__).resolve().parents[1]
    беды = []
    for имя in ФАЙЛЫ:
        путь = корень / имя
        if not путь.exists():
            continue
        дерево = ast.parse(путь.read_text(encoding="utf-8"))
        for узел in ast.walk(дерево):
            if isinstance(узел, ast.Name) and узел.id == "_" and isinstance(узел.ctx, ast.Store):
                беды.append(f"{имя}:{узел.lineno} — присваивание")
            if isinstance(узел, ast.arg) and узел.arg == "_":
                беды.append(f"{имя}:{узел.lineno} — довод функции")

    assert not беды, "имя переводчика затёрто: " + "; ".join(беды[:5])
