"""Проверки готовности окружения.

Поиск по PATH подменяется: иначе проверки зависели бы от того, что стоит
на машине, где их гоняют, и на сборочном раннере вели бы себя иначе,
чем на рабочей.
"""

import sys

from runner.preflight import НУЖНОЕ, как_поставить_qt, чего_не_хватает


def всё_есть(что: str) -> str:
    return "/usr/bin/" + что


def ничего_нет(что: str) -> None:
    return None


def test_когда_всё_на_месте_молчим():
    assert чего_не_хватает(искать=всё_есть) == []


def test_нехватка_называется_и_объясняется():
    """«Не найдено» без объяснения отправляет человека в поиск. Он должен
    узнать и что поставить, и зачем оно.
    """
    итог = чего_не_хватает(искать=ничего_нет)
    assert len(итог) == len(НУЖНОЕ)
    for нехватка in итог:
        assert нехватка.зачем.strip()
        assert нехватка.как.strip()
        assert нехватка.чего in str(нехватка)


def test_советы_разные_на_разных_системах():
    """Совет `brew install` в Windows бесполезен ровно там, где нужен:
    его читают, потому что не знают, что делать.
    """
    итог = чего_не_хватает(искать=ничего_нет)
    советы = " ".join(н.как for н in итог)
    if sys.platform == "win32":
        assert "winget" in советы or "pip" in советы
        assert "brew" not in советы
    elif sys.platform == "darwin":
        assert "brew" in советы
    else:
        assert "apt" in советы or "pipx" in советы


def test_node_объяснён_отдельно():
    """Без node YouTube отдаёт раскадровки, и это выглядит как «сломался
    интернет». Такое надо назвать словами.
    """
    итог = {н.чего: н for н in чего_не_хватает(искать=ничего_нет)}
    assert "node" in итог
    assert "раскадровки" in итог["node"].зачем


def test_совет_по_qt_указывает_на_нынешний_интерпретатор():
    # Настоящий случай: в подсказке стоял `.venv/Scripts/python.exe` —
    # путь, которого на Linux и маке не существует.
    assert sys.executable in как_поставить_qt()
    assert "PySide6" in как_поставить_qt()
