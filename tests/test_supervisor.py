"""Проверки надзора за потомком.

Это арифметика над отметками времени — ровно та категория, которую надо
покрывать плотно: ошибка здесь не роняет программу, а тихо меняет поведение.
Слишком строгий предел убивает здоровые загрузки, слишком мягкий пропускает
зависание на девять часов. И то и другое замечаешь не сразу.
"""

import pytest

from core.supervisor import (
    ProcessState,
    RetryPolicy,
    Verdict,
    WatchdogPolicy,
    judge,
    next_delay,
    should_retry,
)

ПОЛИТИКА = WatchdogPolicy(silence_limit=180.0, total_limit=None)


def состояние(*, начат=0.0, вывод=0.0, сейчас=0.0, вышел=False, код=None):
    return ProcessState(
        started_at=начат, last_output_at=вывод, now=сейчас, exited=вышел, exit_code=код
    )


# --- живой процесс ----------------------------------------------------------


def test_молчащий_в_пределах_допустимого_жив():
    assert judge(состояние(вывод=100.0, сейчас=200.0), ПОЛИТИКА) is Verdict.RUNNING


def test_ровно_на_пределе_ещё_жив():
    # Строгое превышение, а не «больше или равно»: иначе на границе поведение
    # зависело бы от того, успела ли проверка на миллисекунду раньше.
    assert judge(состояние(вывод=0.0, сейчас=180.0), ПОЛИТИКА) is Verdict.RUNNING


def test_на_волосок_за_пределом_уже_завис():
    assert judge(состояние(вывод=0.0, сейчас=180.001), ПОЛИТИКА) is Verdict.STALLED


# --- завершение -------------------------------------------------------------


def test_код_ноль_это_успех():
    assert judge(состояние(сейчас=10.0, вышел=True, код=0), ПОЛИТИКА) is Verdict.OK


def test_ненулевой_код_это_отказ():
    assert judge(состояние(сейчас=10.0, вышел=True, код=1), ПОЛИТИКА) is Verdict.FAILED


def test_завершившийся_после_долгого_молчания_судится_по_коду():
    # Результат уже получен, снимать нечего — даже если перед этим он молчал час.
    итог = judge(состояние(вывод=0.0, сейчас=100_000.0, вышел=True, код=0), ПОЛИТИКА)
    assert итог is Verdict.OK


# --- общий предел -----------------------------------------------------------


def test_общий_предел_срабатывает_даже_у_говорливого():
    политика = WatchdogPolicy(silence_limit=180.0, total_limit=3600.0)
    # Процесс исправно что-то говорит, но идёт уже дольше потолка.
    итог = judge(состояние(вывод=3600.0, сейчас=3600.5), политика)
    assert итог is Verdict.TIMED_OUT


def test_без_общего_предела_говорливый_живёт_сколько_угодно():
    итог = judge(состояние(вывод=100_000.0, сейчас=100_000.0), ПОЛИТИКА)
    assert итог is Verdict.RUNNING


# --- приговоры --------------------------------------------------------------


@pytest.mark.parametrize(
    "приговор,финальный,снимать",
    [
        (Verdict.RUNNING, False, False),
        (Verdict.OK, True, False),
        (Verdict.FAILED, True, False),
        (Verdict.STALLED, True, True),
        (Verdict.TIMED_OUT, True, True),
    ],
)
def test_свойства_приговоров(приговор, финальный, снимать):
    assert приговор.is_final is финальный
    assert приговор.needs_kill is снимать


# --- отказ на бессмысленных данных ------------------------------------------


@pytest.mark.parametrize("предел", [0, -1, -0.5])
def test_отказ_на_неположительном_пределе_молчания(предел):
    with pytest.raises(ValueError):
        WatchdogPolicy(silence_limit=предел)


def test_отказ_на_выводе_раньше_запуска():
    with pytest.raises(ValueError):
        состояние(начат=10.0, вывод=5.0, сейчас=20.0)


def test_отказ_на_сейчас_раньше_запуска():
    with pytest.raises(ValueError):
        состояние(начат=10.0, вывод=10.0, сейчас=5.0)


# --- повторы ----------------------------------------------------------------


def test_первая_попытка_без_паузы():
    assert next_delay(1, RetryPolicy()) == 0.0


def test_паузы_растут():
    политика = RetryPolicy(first_delay=60.0, factor=2.0, max_delay=900.0)
    assert [next_delay(n, политика) for n in (2, 3, 4)] == [60.0, 120.0, 240.0]


def test_паузы_упираются_в_потолок():
    # Долбить YouTube чаще при подряд идущих отказах — верный способ
    # получить блокировку надолго.
    политика = RetryPolicy(first_delay=60.0, factor=2.0, max_delay=300.0)
    assert next_delay(10, политика) == 300.0


def test_отказ_на_нулевой_попытке():
    with pytest.raises(ValueError):
        next_delay(0, RetryPolicy())


def test_успех_не_повторяем():
    assert should_retry(1, Verdict.OK, RetryPolicy()) is False


@pytest.mark.parametrize("приговор", [Verdict.FAILED, Verdict.STALLED, Verdict.TIMED_OUT])
def test_неудачу_повторяем_пока_есть_попытки(приговор):
    политика = RetryPolicy(max_attempts=3)
    assert should_retry(1, приговор, политика) is True
    assert should_retry(2, приговор, политика) is True
    assert should_retry(3, приговор, политика) is False


def test_нельзя_решать_о_повторе_пока_потомок_работает():
    with pytest.raises(ValueError):
        should_retry(1, Verdict.RUNNING, RetryPolicy())


# --- настоящие случаи -------------------------------------------------------


def test_настоящий_случай_2026_08_29_зависание_на_девять_часов():
    """27–29.08 процессы yt-dlp висели с нулевым временем ЦП и нулём сетевых
    соединений: один 554 минуты, другой 111. Собственный `--socket-timeout`
    их не брал, предел выполнения задания тоже.

    Надзорщик обязан опознать это по тишине задолго до того, как пропадут сутки.
    """
    девять_часов = 554 * 60.0
    итог = judge(состояние(вывод=0.0, сейчас=девять_часов), ПОЛИТИКА)

    assert итог is Verdict.STALLED
    assert итог.needs_kill


def test_настоящий_случай_2026_08_16_длинный_ролик_не_считается_зависшим():
    """Ролик SoyuzUS на 2 часа 49 минут и 4,7 ГБ качается совершенно законно.

    Предел по общей длительности убил бы его ни за что — а он в архиве нужен.
    Отличает его от зависшего только то, что он всё время что-то говорит.
    """
    два_часа_сорок_девять = 169 * 60.0
    # Загрузка идёт: последняя строка прогресса была секунду назад.
    итог = judge(состояние(вывод=два_часа_сорок_девять - 1, сейчас=два_часа_сорок_девять), ПОЛИТИКА)

    assert итог is Verdict.RUNNING


def test_настоящий_случай_2026_08_16_паузы_между_роликами_не_зависание():
    """Между роликами скрипт спит 15–45 секунд, чтобы не ловить блокировку.

    Предел молчания обязан быть заметно больше самой длинной законной паузы,
    иначе надзорщик начнёт убивать здоровую выкачку на ровном месте.
    """
    самая_длинная_пауза = 45.0
    итог = judge(состояние(вывод=0.0, сейчас=самая_длинная_пауза), ПОЛИТИКА)

    assert итог is Verdict.RUNNING
    assert ПОЛИТИКА.silence_limit > самая_длинная_пауза * 3
