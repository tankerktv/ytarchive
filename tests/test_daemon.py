"""Проверки непрерывной работы без планировщика.

Часы и сон поддельные: настоящие превратили бы проверку паузы в получасовое
ожидание. Проход тоже подставной — здесь проверяется цикл, а не выкачка.

Главное, что сторожится, — остановка. Она пришла на смену кнопке планировщика,
и если она думает часами или не срабатывает вовсе, человеку остаётся только
снимать процесс из диспетчера задач.
"""

import pytest

from core.flow import ChannelResult, SessionSummary
from core.schedule import Rhythm
from runner import daemon
from runner.daemon import ask_stop, clear_stop, daemon_running, run_forever, stop_requested
from runner.lockfile import acquire

РИТМ = Rhythm(idle=1800.0, busy=60.0, trouble=3600.0)

#: Пауза дробится на секунды, поэтому попадание в неё не идеально точное.
ЗАПАС = 2.0


class Часы:
    """Время двигается только сном — цикл не может «зависнуть в реальности»."""

    def __init__(self) -> None:
        self.сейчас = 0.0

    def __call__(self) -> float:
        return self.сейчас

    def спать(self, сколько: float) -> None:
        self.сейчас += max(сколько, 0.001)


def итог(*, скачано: int = 0, нужен_человек: bool = False) -> SessionSummary:
    if нужен_человек:
        return SessionSummary(
            results=(ChannelResult(channel="X", stopped_reason="нужен вход в аккаунт"),)
        )
    return SessionSummary(results=(ChannelResult(channel="X", downloaded=скачано),))


class Проход:
    """Подставной проход: считает вызовы, запоминает способ остановиться
    и умеет что-нибудь сделать посреди работы."""

    def __init__(self, ответ=None, посреди=None) -> None:
        self.сколько = 0
        self.ответ = ответ or итог()
        self.посреди = посреди
        self.способ_остановиться = None

    def __call__(self, should_stop):
        self.сколько += 1
        self.способ_остановиться = should_stop
        if self.посреди is not None:
            self.посреди(self.сколько)
        return self.ответ


def запуск(проход, tmp_path, часы, **kwargs):
    return run_forever(
        проход, tools_dir=tmp_path, rhythm=РИТМ, sleep=часы.спать, clock=часы, **kwargs
    )


# --- обычный ход ------------------------------------------------------------


def test_делает_заданное_число_проходов(tmp_path):
    проход, часы = Проход(), Часы()
    assert запуск(проход, tmp_path, часы, passes=3) == 3
    assert проход.сколько == 3


def test_после_удачного_прохода_пауза_короткая(tmp_path):
    """Иначе выкачка растянется: в очереди почти наверняка осталось ещё."""
    проход, часы = Проход(ответ=итог(скачано=5)), Часы()
    запуск(проход, tmp_path, часы, passes=2)
    assert часы.сейчас == pytest.approx(РИТМ.busy, abs=ЗАПАС)


def test_холостой_проход_ждёт_дольше(tmp_path):
    проход, часы = Проход(), Часы()
    запуск(проход, tmp_path, часы, passes=2)
    assert часы.сейчас == pytest.approx(РИТМ.idle, abs=ЗАПАС)


def test_когда_нужен_человек_ждём_дольше_всего(tmp_path):
    # Долбиться в истёкшие куки каждые полчаса — так и зарабатывается
    # «подтвердите, что вы не бот».
    проход, часы = Проход(ответ=итог(нужен_человек=True)), Часы()
    запуск(проход, tmp_path, часы, passes=2)
    assert часы.сейчас == pytest.approx(РИТМ.trouble, abs=ЗАПАС)


def test_после_последнего_прохода_не_ждём_впустую(tmp_path):
    """Уходя, спать незачем: это было бы получасовое ничто перед выходом."""
    проход, часы = Проход(), Часы()
    запуск(проход, tmp_path, часы, passes=1)
    assert часы.сейчас == 0.0


# --- остановка --------------------------------------------------------------


def test_просьба_во_время_прохода_прекращает_цикл(tmp_path):
    """Флаг, поставленный пока идёт выкачка, обязан остановить всё,
    а не только текущий канал.
    """
    проход = Проход(посреди=lambda _: ask_stop(tmp_path))
    часы = Часы()

    assert запуск(проход, tmp_path, часы, passes=5) == 1
    assert проход.сколько == 1


def test_просьба_во_время_паузы_не_ждёт_её_конца(tmp_path):
    """Пауза бывает часовой. Ждать её конца значит не остановиться вовсе."""
    проход = Проход(посреди=lambda н: ask_stop(tmp_path) if н == 1 else None)
    часы = Часы()
    запуск(проход, tmp_path, часы, passes=5)

    assert часы.сейчас < РИТМ.idle, "досидели паузу до конца вместо остановки"


def test_проход_получает_способ_остановиться(tmp_path):
    """Без этого просьба дошла бы только до конца текущего канала — а он
    бывает на шестьсот роликов.
    """
    проход, часы = Проход(), Часы()
    запуск(проход, tmp_path, часы, passes=1)

    спросить = проход.способ_остановиться
    assert callable(спросить)
    assert спросить() is False
    ask_stop(tmp_path)
    assert спросить() is True
    clear_stop(tmp_path)


def test_флаг_убирается_за_собой(tmp_path):
    """Оставленный флаг встретит следующий запуск немедленной остановкой,
    и человек будет жать «Пуск» в недоумении.
    """
    проход = Проход(посреди=lambda _: ask_stop(tmp_path))
    запуск(проход, tmp_path, Часы(), passes=3)
    assert not stop_requested(tmp_path)


def test_оставшийся_с_прошлого_раза_флаг_не_мешает_старту(tmp_path):
    ask_stop(tmp_path)
    проход, часы = Проход(), Часы()

    assert запуск(проход, tmp_path, часы, passes=1) == 1, "старый флаг не дал начать"
    assert проход.сколько == 1


# --- один демон -------------------------------------------------------------


def test_второй_демон_не_заводится(tmp_path):
    """Автозапуск и кнопка «Пуск» легко дают двух: они не сговариваются."""
    занято, _ = acquire(tmp_path / daemon.ИМЯ_ЗАМКА)
    assert занято is not None

    проход, часы = Проход(), Часы()
    сообщения = []
    сделано = запуск(проход, tmp_path, часы, passes=3, on_message=сообщения.append)
    занято.release()

    assert сделано == 0
    assert проход.сколько == 0
    assert any("уже работает" in m for m in сообщения)


def test_работающий_демон_виден_снаружи(tmp_path):
    """По этому окно понимает, показывать «Пуск» или «Стоп»."""
    assert not daemon_running(tmp_path)

    замок, _ = acquire(tmp_path / daemon.ИМЯ_ЗАМКА)
    assert daemon_running(tmp_path)

    замок.release()
    assert not daemon_running(tmp_path)


def test_замок_демона_не_протухает_за_долгий_проход(tmp_path, monkeypatch):
    """Настоящий случай 02.09: проход шёл двадцать минут, а замок демона был
    записан один раз при старте. Через десять минут он считался брошенным —
    окно показывало «обход не запущен» и предлагало завести второй.

    Отметка привязана к вопросу «не пора ли остановиться»: его задают
    постоянно, в том числе из самой выкачки.
    """
    from runner.lockfile import read_lock

    monkeypatch.setattr(daemon, "ОТМЕТКА", 0.0)  # отмечаться на каждый вопрос
    метки = []

    def долгий_проход(should_stop):
        for _ in range(3):
            should_stop()
            метки.append(read_lock(tmp_path / daemon.ИМЯ_ЗАМКА).heartbeat)
        return итог()

    run_forever(
        долгий_проход, tools_dir=tmp_path, rhythm=РИТМ,
        sleep=Часы().спать, clock=Часы(), passes=1,
    )

    assert метки[0] < метки[-1], "замок не обновлялся, пока шёл проход"


def test_после_ухода_замок_свободен(tmp_path):
    запуск(Проход(), tmp_path, Часы(), passes=1)

    снова, _ = acquire(tmp_path / daemon.ИМЯ_ЗАМКА)
    assert снова is not None, "замок остался занятым после выхода"
    снова.release()
