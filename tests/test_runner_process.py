"""Проверки обёртки над процессами.

Здесь, в отличие от ядра, поднимаются настоящие потомки — иначе проверять
нечего: вся суть модуля в работе с подсистемой процессов. Потомки крошечные,
пределы взяты в долях секунды, поэтому весь файл укладывается в пару секунд.

Каждая проверка соответствует одному из трёх уроков, оплаченных простоем
27–29.08.2026: пустой ввод, непрерывное вычитывание, снятие с проверкой.
"""

import sys
import time

import pytest

from core.supervisor import Verdict, WatchdogPolicy
from runner.process import run_watched

#: Здесь поднимаются настоящие процессы — это не ядро, и быстро не будет.
pytestmark = pytest.mark.slow

#: Для обычных проверок предел заведомо недостижим: они про поведение,
#: а не про сроки. Тесный предел делал их шаткими — на нагруженной машине
#: короткий потомок изредка не успевал сказать ни слова за секунду,
#: и его снимали как зависшего. Шаткий тест хуже падающего: он приучает
#: не верить красному.
БЫСТРАЯ = WatchdogPolicy(silence_limit=10.0, kill_grace=2.0)

#: Для проверок снятия — отдельная политика. Потомок там сначала подаёт
#: голос, и лишь потом замолкает, поэтому отсчёт не зависит от того,
#: как быстро запустился интерпретатор.
СТРОГАЯ = WatchdogPolicy(silence_limit=2.0, kill_grace=2.0)


def питон(код: str) -> list[str]:
    return [sys.executable, "-c", код]


def test_успешный_потомок():
    итог = run_watched(питон("print('готово')"), БЫСТРАЯ)
    assert итог.verdict is Verdict.OK
    assert итог.exit_code == 0
    assert итог.is_ok
    assert not итог.killed


def test_упавший_потомок():
    итог = run_watched(питон("import sys; sys.exit(3)"), БЫСТРАЯ)
    assert итог.verdict is Verdict.FAILED
    assert итог.exit_code == 3
    assert not итог.is_ok


def test_вывод_собирается():
    итог = run_watched(питон("print('первая'); print('вторая')"), БЫСТРАЯ)
    assert "первая" in итог.text
    assert "вторая" in итог.text


def test_стандартная_ошибка_попадает_в_тот_же_поток():
    # yt-dlp пишет и туда и туда; разделять их значит потерять порядок событий.
    итог = run_watched(питон("import sys; print('из ошибки', file=sys.stderr)"), БЫСТРАЯ)
    assert "из ошибки" in итог.text


# --- разделение потоков -----------------------------------------------------


ОБА_ПОТОКА = "import sys; print('данные'); print('шум', file=sys.stderr)"


def test_при_слитых_потоках_stdout_повторяет_общий_вывод():
    """Разделения не просили — значит `stdout_lines` не должен быть пустым
    сюрпризом для тех, кто их читает.
    """
    итог = run_watched(питон(ОБА_ПОТОКА), БЫСТРАЯ)
    assert "данные" in итог.stdout_text
    assert "шум" in итог.stdout_text


def test_разделённый_stdout_не_содержит_stderr():
    """Настоящий случай 02.09: yt-dlp пишет в stderr «Deprecated Feature: ...»,
    и перепись канала засчитала эту строку в потерянные ролики.
    """
    итог = run_watched(питон(ОБА_ПОТОКА), БЫСТРАЯ, separate_streams=True)
    assert "данные" in итог.stdout_text
    assert "шум" not in итог.stdout_text


def test_разделение_не_теряет_stderr_из_общего_вывода():
    # Разбор бед смотрит в `text` — там обязано остаться всё.
    итог = run_watched(питон(ОБА_ПОТОКА), БЫСТРАЯ, separate_streams=True)
    assert "шум" in итог.text
    assert "данные" in итог.text


def test_говорящий_только_в_stderr_считается_живым():
    """Иначе разделение обернулось бы снятием живого потомка: молчание
    в stdout — не признак зависания.
    """
    код = (
        "import sys, time\n"
        "for _ in range(6):\n"
        "    print('жив', file=sys.stderr); sys.stderr.flush(); time.sleep(0.1)\n"
    )
    итог = run_watched(
        питон(код),
        WatchdogPolicy(silence_limit=0.4, total_limit=10.0, kill_grace=1.0),
        separate_streams=True,
    )
    assert итог.verdict is Verdict.OK, "живого потомка сняли за молчание в stdout"
    assert not итог.killed


def test_обратный_вызов_получает_строки():
    собрано: list[str] = []
    run_watched(питон("print('раз'); print('два')"), БЫСТРАЯ, on_line=собрано.append)
    assert "раз" in собрано
    assert "два" in собрано


def test_падение_обратного_вызова_не_роняет_выкачку():
    # Ошибка в интерфейсе не должна стоить пользователю ночи скачивания.
    def сломанный(_: str) -> None:
        raise RuntimeError("интерфейс сломался")

    итог = run_watched(питон("print('всё равно работаем')"), БЫСТРАЯ, on_line=сломанный)
    assert итог.verdict is Verdict.OK


# --- уроки, оплаченные простоем ---------------------------------------------


def test_молчащий_потомок_снимается():
    """Урок третий: зависшего надо снять, и снятие проверить.

    Потомок молчит дольше предела — надзорщик обязан его убить, а не ждать
    вечно, как это делал скрипт до переписывания.
    """
    # Сначала подаёт голос, потом замолкает — так отсчёт молчания начинается
    # от заведомо известной точки, а не от запуска интерпретатора.
    код = "import time,sys; print('начал', flush=True); time.sleep(30)"
    начало = time.monotonic()
    итог = run_watched(питон(код), СТРОГАЯ)
    прошло = time.monotonic() - начало

    assert итог.verdict is Verdict.STALLED
    assert итог.killed
    assert not итог.kill_failed, "процесс пережил снятие — та самая беда с сиротами"
    assert "начал" in итог.text, "потомок не успел подать голос — проверка не о том"
    assert прошло < 10, f"снимали слишком долго: {прошло:.1f} с"


def test_говорливый_потомок_не_снимается():
    """Долгая, но живая работа не должна прерываться.

    Ролик на 4,7 ГБ качается два часа сорок девять минут — предел по общей
    длительности убил бы его ни за что. Отличает живого только то,
    что он говорит.
    """
    код = "import time,sys\nfor i in range(6):\n    print(i, flush=True)\n    time.sleep(0.3)"
    итог = run_watched(питон(код), БЫСТРАЯ)

    assert итог.verdict is Verdict.OK
    assert not итог.killed
    assert итог.elapsed > 1.5, "потомок отработал слишком быстро, проверка бессмысленна"


def test_настоящий_случай_потомок_читающий_ввод_не_виснет():
    """Урок первый: потомку даётся ПУСТОЙ ввод, а не унаследованный.

    Процесс, ждущий ответа на приглашение, которого никто не видит, выглядит
    ровно как наши сироты: нулевое время ЦП, ноль соединений, часы простоя.
    С пустым вводом чтение сразу возвращает конец файла.
    """
    итог = run_watched(
        питон("import sys; data = sys.stdin.read(); print('прочитано', len(data))"),
        БЫСТРАЯ,
    )

    assert итог.verdict is Verdict.OK
    assert "прочитано 0" in итог.text


def test_настоящий_случай_обильный_вывод_не_забивает_трубу():
    """Урок второй: вывод вычитывается непрерывно, отдельным потоком.

    Если этого не делать, труба переполняется и потомок встаёт на записи.
    Внешне — снова «зависание» без единой причины в журнале.
    """
    код = "for i in range(20000): print('строка', i)"
    итог = run_watched(питон(код), БЫСТРАЯ)

    assert итог.verdict is Verdict.OK, "потомок встал на записи — труба не вычитывалась"
    # В памяти держим только хвост, а не все двадцать тысяч строк.
    assert len(итог.lines) <= 500
    assert "строка 19999" in итог.text


def test_общий_предел_снимает_даже_говорливого():
    политика = WatchdogPolicy(silence_limit=30.0, total_limit=1.0, kill_grace=2.0)
    код = "import time,sys\nwhile True:\n    print('живу', flush=True)\n    time.sleep(0.1)"
    итог = run_watched(питон(код), политика)

    assert итог.verdict is Verdict.TIMED_OUT
    assert итог.killed


@pytest.mark.parametrize("предел", [0.0, -1.0])
def test_отказ_на_бессмысленном_пределе(предел):
    with pytest.raises(ValueError):
        WatchdogPolicy(silence_limit=предел)


def test_настоящий_случай_2026_08_30_кириллица_в_названии_не_портится():
    """yt-dlp на Windows печатает кириллицу в системной кодировке, если его
    не попросить об обратном. Старый скрипт лечил это переменной окружения,
    а в первой версии обёртки я её не перенёс — и в журнале появилось
    «2026-08-29 - ?? ?????? ????» вместо названия ролика.

    Потомок обязан говорить в UTF-8 независимо от того, что стоит в системе.
    """
    код = "print('Уютный подвальчик — ролик №1')"
    итог = run_watched(питон(код), БЫСТРАЯ)

    assert "Уютный подвальчик" in итог.text
    assert "�" not in итог.text, "в выводе символы замены — кодировка потеряна"
