"""Проверки выбора языка.

Цена ошибки здесь тихая: интерфейс наполовину на чужом языке или молчаливый
откат к русскому у того, кто русского не знает. Ни то, ни другое не падает
и не пишется в журнал — заметит только человек, которому неудобно.
"""

from core.i18n import (
    ЗАПАСНОЙ,
    ИСХОДНЫЙ,
    НАЗВАНИЯ,
    СИСТЕМНЫЙ,
    missing,
    нормализовать,
    orphaned,
    resolve,
    translator,
)

ЕСТЬ = {"en", "de", "es"}


# --- приведение обозначений --------------------------------------------------


def test_обозначения_систем_приводятся_к_основе():
    """Системы называют язык кто во что горазд. Держать словарь на каждую
    страну значило бы переводить одно и то же по десять раз.
    """
    for дано in ("ru_RU.UTF-8", "ru-RU", "RU", "ru"):
        assert нормализовать(дано) == "ru"
    assert нормализовать("pt_BR") == "pt"
    assert нормализовать("en-GB") == "en"


def test_несуразное_обозначение_не_язык():
    for мусор in ("", "   ", "1234", "-", "_US"):
        assert нормализовать(мусор) == ""


# --- выбор языка -------------------------------------------------------------


def test_выбор_человека_важнее_системы():
    assert resolve("de", "ru_RU", ЕСТЬ) == "de"


def test_системный_язык_когда_не_выбрано():
    assert resolve(СИСТЕМНЫЙ, "de_DE", ЕСТЬ) == "de"
    assert resolve("", "es_ES", ЕСТЬ) == "es"


def test_русский_доступен_всегда():
    """Словаря для русского нет и быть не может — строки в исходнике уже
    на нём. Но выбрать его человек должен уметь.
    """
    assert resolve("ru", "en_US", ЕСТЬ) == "ru"
    assert resolve(СИСТЕМНЫЙ, "ru_RU", ЕСТЬ) == ИСХОДНЫЙ


def test_язык_без_словаря_не_подставляется():
    """Иначе интерфейс окажется наполовину на языке, которого не просили."""
    assert resolve("ja", "ja_JP", ЕСТЬ) == ЗАПАСНОЙ


def test_незнакомая_система_даёт_английский():
    # Человек с системой на суахили скорее прочтёт английский, чем русский.
    assert resolve(СИСТЕМНЫЙ, "sw_KE", ЕСТЬ) == "en"


def test_когда_нет_даже_английского():
    assert resolve(СИСТЕМНЫЙ, "sw_KE", set()) == ИСХОДНЫЙ


def test_системный_не_принимается_за_код_языка():
    # Иначе «system» искалось бы среди языков и не находилось.
    assert resolve(СИСТЕМНЫЙ, "de_DE", ЕСТЬ) == "de"


# --- подстановка -------------------------------------------------------------


СЛОВАРИ = {"en": {"Убрать": "Remove", "Каналы": "Channels"}}


def test_перевод_подставляется():
    _ = translator("en", СЛОВАРИ)
    assert _("Убрать") == "Remove"


def test_на_исходном_языке_ничего_не_подставляется():
    _ = translator("ru", СЛОВАРИ)
    assert _("Убрать") == "Убрать"


def test_пропущенный_перевод_возвращает_исходное():
    """Некрасиво, но работает. Исключение посреди отрисовки окна означало бы
    конец работы, а пропуск ловит тест.
    """
    _ = translator("en", СЛОВАРИ)
    assert _("Настройки") == "Настройки"


def test_язык_без_словаря_не_роняет():
    _ = translator("ja", СЛОВАРИ)
    assert _("Убрать") == "Убрать"


# --- полнота словарей --------------------------------------------------------


def test_непереведённое_находится():
    assert missing(СЛОВАРИ["en"], ["Убрать", "Настройки"]) == ["Настройки"]


def test_осиротевший_перевод_находится():
    """След правки русской строки: перевод остался, а строки уже нет.
    Сам по себе безвреден, но рядом наверняка появилась непереведённая.
    """
    assert orphaned(СЛОВАРИ["en"], ["Убрать"]) == ["Каналы"]


def test_у_каждого_языка_есть_имя_на_нём_самом():
    # «Немецкий» ничего не говорит тому, кто ищет слово «Deutsch».
    assert НАЗВАНИЯ["de"] == "Deutsch"
    assert НАЗВАНИЯ["ru"] == "Русский"
    assert all(имя.strip() for имя in НАЗВАНИЯ.values())
