"""Проверки ритма проходов.

Расписание заменило планировщик Windows, и цена ошибки здесь — не «неудобно»,
а «архив собирается неделями» или «нас перестали пускать». Поэтому проверяется
не арифметика, а смысл каждого случая.
"""

import pytest

from core.schedule import Rhythm, next_pause

РИТМ = Rhythm(idle=1800.0, busy=60.0, trouble=3600.0)


def test_после_удачного_прохода_возвращаемся_скоро():
    """В очереди почти наверняка осталось ещё: проход забирает столько,
    сколько успел. Ждать полчаса впустую — растянуть архив на недели.
    """
    assert next_pause(downloaded=5, needs_human=False, rhythm=РИТМ) == РИТМ.busy


def test_когда_ничего_не_нашлось_ждём_дольше():
    # Новые ролики выходят не каждую минуту; частые проверки жгут запросы.
    assert next_pause(downloaded=0, needs_human=False, rhythm=РИТМ) == РИТМ.idle


def test_когда_нужен_человек_ждём_дольше_всего():
    """Куки сами не появятся. Долбиться в стену каждые полчаса — именно так
    и зарабатывается «подтвердите, что вы не бот».
    """
    assert next_pause(downloaded=0, needs_human=True, rhythm=РИТМ) == РИТМ.trouble


def test_беда_перевешивает_удачу():
    """Проход мог забрать половину канала и упереться в истёкшие куки.
    Вернуться через минуту, чтобы упереться снова, — худший из исходов.
    """
    assert next_pause(downloaded=40, needs_human=True, rhythm=РИТМ) == РИТМ.trouble


def test_паузы_обязаны_быть_положительными():
    # Ноль означал бы проход без передышки — это не расписание, а цикл.
    for негодный in (dict(idle=0), dict(busy=-1), dict(trouble=0)):
        with pytest.raises(ValueError):
            Rhythm(**негодный)


def test_удачная_пауза_не_длиннее_холостой():
    """Иначе «нашлась работа» замедляло бы выкачку вместо ускорения —
    ровно наоборот смыслу.
    """
    with pytest.raises(ValueError):
        Rhythm(idle=60.0, busy=600.0)


def test_умолчания_осмысленны():
    ритм = Rhythm()
    assert ритм.busy < ритм.idle < ритм.trouble
