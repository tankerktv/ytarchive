"""Язык интерфейса: узнать системный и раздать переводчик на весь процесс.

Почему не в `core`: там решают, каким языком говорить, а здесь спрашивают
об этом операционную систему. Ядро обязано проверяться без системы с нужной
локалью, поэтому обращения к ней живут отдельно.

Переводчик один на процесс и настраивается один раз при запуске. Таскать его
через все конструкторы окна было бы честнее, но пришлось бы протянуть лишний
довод через полсотни мест — а язык за время работы не меняется.
"""

from __future__ import annotations

import locale
import os
import sys

from core.i18n import ИСХОДНЫЙ, resolve, translator
from core.locales import КАТАЛОГИ

#: Текущий переводчик. До настройки — тождественный: строки в исходнике
#: уже по-русски, и до выбора языка ничего подставлять не надо.
_перевести = str
_язык = ИСХОДНЫЙ


def системный_язык() -> str:
    """Чем говорит система. Пустая строка значит «не смогли узнать».

    На Windows первой спрашиваем саму систему, а не переменные окружения.
    Проверено на себе: запуск из Git Bash приносит `LANG=en_US`, и программа
    на русской машине заговорила бы по-английски. Переменных там обычно нет
    вовсе, а если есть — они от чужой оболочки, а не от человека.

    На линуксе и маке наоборот: переменные и есть настоящий ответ.
    """
    if sys.platform == "win32":
        try:
            import ctypes

            номер = ctypes.windll.kernel32.GetUserDefaultUILanguage()
            найденный = locale.windows_locale.get(номер, "")
            if найденный:
                return найденный
        except (OSError, AttributeError, ValueError):
            pass

    for имя in ("LANGUAGE", "LC_ALL", "LC_MESSAGES", "LANG"):
        значение = os.environ.get(имя, "").strip()
        if значение and значение.lower() not in ("c", "posix"):
            return значение.split(":", 1)[0]

    try:
        язык, _ = locale.getlocale()
        return язык or ""
    except (ValueError, TypeError):
        return ""


def настроить(выбранный: str) -> str:
    """Выбрать язык на весь процесс. Возвращает то, на чём остановились."""
    global _перевести, _язык

    _язык = resolve(выбранный, системный_язык(), КАТАЛОГИ)
    _перевести = translator(_язык, КАТАЛОГИ)
    return _язык


def текущий() -> str:
    return _язык


def _(строка: str) -> str:
    """Перевести строку. Имя короткое намеренно: им обёрнута каждая надпись,
    и длинное сделало бы код нечитаемым."""
    return _перевести(строка)
